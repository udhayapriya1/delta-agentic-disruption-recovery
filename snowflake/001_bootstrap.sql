-- ACCOUNTADMIN is bootstrap-only. No CREATE OR REPLACE or destructive reset.
CREATE DATABASE IF NOT EXISTS DELTA_DEMO;
CREATE SCHEMA IF NOT EXISTS DELTA_DEMO.CUSTOMER_360;
CREATE SCHEMA IF NOT EXISTS DELTA_DEMO.FLIGHT_OPERATIONS;
CREATE SCHEMA IF NOT EXISTS DELTA_DEMO.AGENT_ANALYTICS;
CREATE WAREHOUSE IF NOT EXISTS DELTA_DEMO_WH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
ALTER WAREHOUSE DELTA_DEMO_WH SET WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE;
CREATE ROLE IF NOT EXISTS DELTA_DEMO_APP;
CREATE ROLE IF NOT EXISTS DELTA_DEMO_LOADER;
GRANT USAGE ON WAREHOUSE DELTA_DEMO_WH TO ROLE DELTA_DEMO_APP;
GRANT USAGE ON WAREHOUSE DELTA_DEMO_WH TO ROLE DELTA_DEMO_LOADER;
GRANT USAGE ON DATABASE DELTA_DEMO TO ROLE DELTA_DEMO_APP;
GRANT USAGE ON DATABASE DELTA_DEMO TO ROLE DELTA_DEMO_LOADER;
GRANT USAGE ON SCHEMA DELTA_DEMO.CUSTOMER_360 TO ROLE DELTA_DEMO_APP;
GRANT USAGE ON ALL SCHEMAS IN DATABASE DELTA_DEMO TO ROLE DELTA_DEMO_LOADER;
CREATE TABLE IF NOT EXISTS DELTA_DEMO.CUSTOMER_360.PASSENGER_SOURCES (SOURCE_ID VARCHAR, PASSENGER_ID VARCHAR, SURNAME VARCHAR, EMAIL VARCHAR, EMAIL_VERIFIED BOOLEAN, SKYMILES VARCHAR, TIER VARCHAR, PNR VARCHAR, CONSENT BOOLEAN, CABIN VARCHAR, SPECIAL VARCHAR, UPDATED_AT TIMESTAMP_TZ);
CREATE TABLE IF NOT EXISTS DELTA_DEMO.CUSTOMER_360.LOYALTY_PROFILES (PASSENGER_ID VARCHAR, TIER VARCHAR, MILES NUMBER, SOURCE_TIMESTAMP TIMESTAMP_TZ);
CREATE TABLE IF NOT EXISTS DELTA_DEMO.CUSTOMER_360.TRAVEL_HISTORY (TRAVEL_ID VARCHAR, PASSENGER_ID VARCHAR, ROUTE VARCHAR, TRAVEL_DATE DATE);
CREATE TABLE IF NOT EXISTS DELTA_DEMO.FLIGHT_OPERATIONS.DISRUPTION_EVENTS (EVENT_ID VARCHAR, PNR VARCHAR, STATUS VARCHAR, REASON VARCHAR, SOURCE_TIMESTAMP TIMESTAMP_TZ);
CREATE TABLE IF NOT EXISTS DELTA_DEMO.AGENT_ANALYTICS.EXECUTION_RUNS (RUN_ID VARCHAR, CREATED_AT TIMESTAMP_TZ, RESULT VARIANT);
GRANT SELECT ON TABLE DELTA_DEMO.CUSTOMER_360.LOYALTY_PROFILES TO ROLE DELTA_DEMO_APP;
GRANT SELECT ON TABLE DELTA_DEMO.CUSTOMER_360.TRAVEL_HISTORY TO ROLE DELTA_DEMO_APP;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DELTA_DEMO.CUSTOMER_360 TO ROLE DELTA_DEMO_LOADER;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DELTA_DEMO.FLIGHT_OPERATIONS TO ROLE DELTA_DEMO_LOADER;
-- Explicitly grant DELTA_DEMO_APP/LOADER to the authorized user separately;
-- never grant ACCOUNTADMIN to the application. Runtime needs no write privileges.
CREATE TABLE IF NOT EXISTS DELTA_DEMO.CUSTOMER_360.CONSENT (PASSENGER_ID VARCHAR, PURPOSE VARCHAR, ALLOWED BOOLEAN, SOURCE_TIMESTAMP TIMESTAMP_TZ);
CREATE TABLE IF NOT EXISTS DELTA_DEMO.FLIGHT_OPERATIONS.FLIGHTS (FLIGHT_ID VARCHAR, ROUTE VARCHAR, CABIN VARCHAR, DEPARTURE_AT TIMESTAMP_TZ, STATUS VARCHAR);
CREATE TABLE IF NOT EXISTS DELTA_DEMO.FLIGHT_OPERATIONS.BOOKING_SNAPSHOTS (PNR VARCHAR, PASSENGER_ID VARCHAR, FLIGHT_ID VARCHAR, SOURCE_TIMESTAMP TIMESTAMP_TZ);
-- Flight/booking snapshots are synthetic audit sources, not live seat inventory.
GRANT SELECT ON TABLE DELTA_DEMO.CUSTOMER_360.CONSENT TO ROLE DELTA_DEMO_APP;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DELTA_DEMO.CUSTOMER_360 TO ROLE DELTA_DEMO_LOADER;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DELTA_DEMO.FLIGHT_OPERATIONS TO ROLE DELTA_DEMO_LOADER;
